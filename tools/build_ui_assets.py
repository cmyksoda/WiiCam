"""Deterministically rasterize replaceable artwork and a caller-selected local font.

Generated font bitmaps inherit the selected font's licensing restrictions.
No font is copied into source control. This build requires an explicit font path.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--font', required=True)
args = parser.parse_args()
font_path = Path(args.font).expanduser().resolve()
if not font_path.is_file():
    parser.error('font file not found; set WC04_FONT to a licensed local font')
output = ROOT / 'build/ui_assets.h'
output.parent.mkdir(exist_ok=True)
lines = ['/* Generated by tools/build_ui_assets.py; do not edit. */',
         'typedef struct { unsigned offset; short x, y, w, h, advance; } UiGlyph;']

def array(name, values):
    lines.append(f'static const unsigned char {name}[] = {{')
    for at in range(0, len(values), 32):
        lines.append(','.join(str(v) for v in values[at:at+32]) + ',')
    lines.append('};')

pixels = bytearray()
for size in (12, 15, 18, 20, 22, 25, 28, 48):
    font = ImageFont.truetype(str(font_path), size)
    entries = []
    for c in range(32, 127):
        text = chr(c)
        x0, y0, x1, y1 = font.getbbox(text, anchor='ls')
        w, h = x1-x0, y1-y0
        mask = Image.new('L', (w, h))
        ImageDraw.Draw(mask).text((-x0, -y0), text, font=font, anchor='ls', fill=255)
        ink = mask.getbbox()
        if ink:
            mask = mask.crop(ink)
            x0 += ink[0]
            y0 += ink[1]
            w, h = mask.size
        entries.append(f'{{{len(pixels)},{x0},{y0},{w},{h},{round(font.getlength(text))}}}')
        pixels.extend(mask.tobytes())
    lines.append(f'static const UiGlyph ui_font_{size}[] = {{\n' + ',\n'.join(entries) + '\n};')
array('ui_font_pixels', pixels)
home = Image.open(ROOT / 'assets/wii-home-glyph-mask.png').convert('L')
home.thumbnail((18, 17), Image.Resampling.LANCZOS)
lines.append(f'#define UI_HOME_WIDTH {home.width}\n#define UI_HOME_HEIGHT {home.height}')
array('ui_home', home.tobytes())
bars = Image.open(ROOT / 'assets/color-bars.png').convert('RGB').resize((360, 270), Image.Resampling.NEAREST)
array('ui_bars', bars.tobytes())
output.write_text('\n'.join(lines) + '\n')
(ROOT / 'build/ui-font.json').write_text(json.dumps({
    'font': str(font_path), 'name': ImageFont.truetype(str(font_path), 20).getname(),
    'sha256': hashlib.sha256(font_path.read_bytes()).hexdigest(),
    'redistribution': 'Not established by this build. Generated glyph bitmaps are font-derived.'
}, indent=2) + '\n')
print(f'UI assets: {output}; font: {font_path.name} (review license before distribution)')
